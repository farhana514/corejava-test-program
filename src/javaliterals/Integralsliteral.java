package javaliterals;

public class Integralsliteral {
	//Decimal integrals
	int a1 = 1234;
	int a2 = 789;
	
	
	//octal integrals
	int a3 = 567;
	int a4 = 456;
	int a5 = 356;
	int a6 = 234;
	
	//Hexa decimal
	int a7 = 0x456;
	int a8 = 0x567;
	int a9 = 0xa1b2;
	int a10 = 0xfaa;
	int a11 = 0xDAD;
	int a12 = 0xBCE;
	//int a13 = 0xbeer;
	
	//binary integrals
	int a14 = 0b1010;
	int a15 = 0b1101;
	int a16 = 0b1111;
	int a17 = 0b00001;
	
	
	

	public static void main(String[] args) {
		Integralsliteral g = new Integralsliteral ();
		System.out.println(g.a1);
		System.out.println(g.a2);
		System.out.println(g.a3);
		System.out.println(g.a4);
		System.out.println(g.a5);
		System.out.println(g.a6);
		System.out.println(g.a7);
		System.out.println(g.a8);
		System.out.println(g.a9);
		System.out.println(g.a10);
		System.out.println(g.a11);
		System.out.println(g.a12);
		System.out.println(g.a14);
		System.out.println(g.a15);
		System.out.println(g.a16);
		System.out.println(g.a17);
		
		
		

	}

}
